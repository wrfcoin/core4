//! Governance proposal implementation
//!
//! This module provides the proposal data structures and functionality.

use crate::governance::voting::{Vote, VotingPower};
use anyhow::Result;
use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use std::collections::HashMap;

/// Type of governance proposal
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub enum ProposalType {
    /// Protocol parameter change proposal
    ParameterChange {
        /// Parameter name
        parameter: String,

        /// New parameter value
        value: String,
    },

    /// Protocol upgrade proposal
    ProtocolUpgrade {
        /// New protocol version
        version: String,

        /// Hash of the protocol upgrade code
        code_hash: String,

        /// Activation height
        activation_height: u64,
    },

    /// Funding proposal
    FundingProposal {
        /// Recipient address
        recipient: String,

        /// Amount to fund
        amount: u64,

        /// Purpose of the funding
        purpose: String,
    },

    /// Text proposal (signaling only)
    Text {
        /// Text content
        content: String,
    },
}

/// Status of a governance proposal
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub enum ProposalStatus {
    /// Proposal is active and accepting votes
    Active,

    /// Proposal has passed and been executed
    Executed,

    /// Proposal has passed but not yet executed
    Passed,

    /// Proposal has been rejected
    Rejected,

    /// Proposal has failed due to other reasons (e.g., lack of quorum)
    Failed,

    /// Proposal has been cancelled by the proposer
    Cancelled,
}

/// A governance proposal
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Proposal {
    /// Unique identifier
    pub id: String,

    /// Proposer address
    pub proposer: String,

    /// Proposal title
    pub title: String,

    /// Proposal description
    pub description: String,

    /// Proposal type with specific details
    pub proposal_type: ProposalType,

    /// Creation time
    pub creation_time: DateTime<Utc>,

    /// End of voting period
    pub end_time: DateTime<Utc>,

    /// Proposal status
    pub status: ProposalStatus,

    /// Token deposit by the proposer
    pub deposit: u64,

    /// Votes on the proposal
    pub votes: HashMap<String, (Vote, VotingPower)>,

    /// Whether this proposal was generated by an AI controller (e.g. `AiEmissionController`).
    /// AI-generated proposals are subject to a challenge period before auto-execution.
    #[serde(default)]
    pub ai_generated: bool,
}

impl Proposal {
    /// Create a new proposal
    pub fn new(
        id: String,
        proposer: String,
        title: String,
        description: String,
        proposal_type: ProposalType,
        creation_time: DateTime<Utc>,
        end_time: DateTime<Utc>,
        deposit: u64,
    ) -> Self {
        Self {
            id,
            proposer,
            title,
            description,
            proposal_type,
            creation_time,
            end_time,
            status: ProposalStatus::Active,
            deposit,
            votes: HashMap::new(),
            ai_generated: false,
        }
    }

    /// Add a vote to the proposal
    pub fn add_vote(&mut self, voter: String, vote: Vote, power: VotingPower) -> Result<()> {
        if self.status != ProposalStatus::Active {
            return Err(anyhow::anyhow!("Proposal is not active"));
        }

        self.votes.insert(voter, (vote, power));
        Ok(())
    }

    /// Count the total votes on the proposal
    pub fn total_votes(&self) -> VotingPower {
        self.votes
            .values()
            .fold(VotingPower::default(), |acc, (_, power)| VotingPower {
                value: acc.value + power.value,
            })
    }

    /// Count the votes by type
    pub fn count_votes(&self) -> (VotingPower, VotingPower, VotingPower, VotingPower) {
        let mut yes = VotingPower::default();
        let mut no = VotingPower::default();
        let mut abstain = VotingPower::default();
        let mut veto = VotingPower::default();

        for (vote, power) in self.votes.values() {
            match vote {
                Vote::Yes => yes.value += power.value,
                Vote::No => no.value += power.value,
                Vote::Abstain => abstain.value += power.value,
                Vote::Veto => veto.value += power.value,
            }
        }

        (yes, no, abstain, veto)
    }

    /// Calculate the approval percentage (Yes votes / (Yes + No + Veto))
    pub fn approval_percentage(&self) -> u64 {
        let (yes, no, _, veto) = self.count_votes();
        let total = yes.value + no.value + veto.value;

        if total == 0 {
            return 0;
        }

        (yes.value * 100) / total
    }

    /// Check if a voter has already voted
    pub fn has_voted(&self, voter: &str) -> bool {
        self.votes.contains_key(voter)
    }

    /// Cancel the proposal (only the proposer can do this)
    pub fn cancel(&mut self, caller: &str) -> Result<()> {
        if caller != self.proposer {
            return Err(anyhow::anyhow!("Only the proposer can cancel"));
        }

        if self.status != ProposalStatus::Active {
            return Err(anyhow::anyhow!("Proposal is not active"));
        }

        self.status = ProposalStatus::Cancelled;
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use chrono::Utc;

    fn make_proposal(proposer: &str) -> Proposal {
        let now = Utc::now();
        Proposal::new(
            "prop-1".to_string(),
            proposer.to_string(),
            "Test".to_string(),
            "desc".to_string(),
            ProposalType::Text { content: "signal".to_string() },
            now,
            now + chrono::Duration::days(7),
            1_000,
        )
    }

    fn power(v: u64) -> VotingPower {
        VotingPower { value: v }
    }

    #[test]
    fn add_vote_yes_no_abstain_veto_counted_correctly() {
        let mut p = make_proposal("alice");
        p.add_vote("a".into(), Vote::Yes, power(100)).unwrap();
        p.add_vote("b".into(), Vote::No, power(40)).unwrap();
        p.add_vote("c".into(), Vote::Abstain, power(10)).unwrap();
        p.add_vote("d".into(), Vote::Veto, power(50)).unwrap();

        let (yes, no, abstain, veto) = p.count_votes();
        assert_eq!(yes.value, 100);
        assert_eq!(no.value, 40);
        assert_eq!(abstain.value, 10);
        assert_eq!(veto.value, 50);
        assert_eq!(p.total_votes().value, 200);
    }

    #[test]
    fn approval_percentage_excludes_abstain() {
        let mut p = make_proposal("alice");
        p.add_vote("a".into(), Vote::Yes, power(60)).unwrap();
        p.add_vote("b".into(), Vote::No, power(30)).unwrap();
        p.add_vote("c".into(), Vote::Abstain, power(999)).unwrap();

        // 60 / (60 + 30 + 0 veto) = 66%
        assert_eq!(p.approval_percentage(), 66);
    }

    #[test]
    fn approval_percentage_zero_when_no_votes() {
        let p = make_proposal("alice");
        assert_eq!(p.approval_percentage(), 0);
    }

    #[test]
    fn add_vote_overwrites_previous_vote_for_same_voter() {
        let mut p = make_proposal("alice");
        p.add_vote("a".into(), Vote::No, power(100)).unwrap();
        p.add_vote("a".into(), Vote::Yes, power(100)).unwrap();

        let (yes, no, _, _) = p.count_votes();
        assert_eq!(yes.value, 100);
        assert_eq!(no.value, 0, "second vote must overwrite first");
    }

    #[test]
    fn has_voted_returns_correct_state() {
        let mut p = make_proposal("alice");
        assert!(!p.has_voted("bob"));
        p.add_vote("bob".into(), Vote::Yes, power(1)).unwrap();
        assert!(p.has_voted("bob"));
    }

    #[test]
    fn add_vote_rejected_when_proposal_not_active() {
        let mut p = make_proposal("alice");
        p.status = ProposalStatus::Passed;
        let err = p.add_vote("a".into(), Vote::Yes, power(1)).unwrap_err();
        assert!(err.to_string().contains("not active"));
    }

    #[test]
    fn cancel_by_proposer_sets_cancelled_status() {
        let mut p = make_proposal("alice");
        p.cancel("alice").unwrap();
        assert_eq!(p.status, ProposalStatus::Cancelled);
    }

    #[test]
    fn cancel_by_non_proposer_returns_error() {
        let mut p = make_proposal("alice");
        let err = p.cancel("bob").unwrap_err();
        assert!(err.to_string().contains("proposer"));
    }

    #[test]
    fn cancel_already_cancelled_proposal_returns_error() {
        let mut p = make_proposal("alice");
        p.cancel("alice").unwrap();
        let err = p.cancel("alice").unwrap_err();
        assert!(err.to_string().contains("not active"));
    }
}
