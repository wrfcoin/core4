#!/usr/bin/env python3
"""Compare per-height state-root JSON files across determinism-matrix legs (#2104).

Each input file maps height -> state_root hex, e.g. produced by
`cargo run -p test_server --example emit_roots`:

    { "0": "fc96...", "1": "e1e0...", ... }

This runs TWO independent checks, and both must pass:

1. **Cross-leg agreement.** No two legs may disagree at any height. Catches
   platform-dependent nondeterminism — hash-map ordering, CPU features, float
   drift across arch/profile/toolchain.

2. **Anchor agreement** (`--expected`). Every leg must also match the committed
   `tests/integration/fixtures/determinism/expected_roots.json`.

Check 2 exists because check 1 alone is unfalsifiable in one specific and
dangerous case. Cross-leg comparison only asks whether the legs agree *with each
other* — so a deterministic change to state-transition semantics shifts every leg
identically, all five still agree, and the gate stays green while the chain's
roots have silently changed. **Five legs agreeing is not five legs being right.**
The anchor is the only thing in this gate that is not regenerated by the same run
it is checking, so it is the only thing that can catch a common-mode shift.

Consequently `--expected` is REQUIRED unless `--no-expected` is passed
explicitly. An anchor that callers may silently omit is an anchor that erodes;
the workflow always passes it. `--no-expected` exists for ad-hoc local diffing of
two arbitrary root files and says so in its output.

    python3 scripts/compare_state_roots.py --expected tests/integration/fixtures/determinism/expected_roots.json roots-*.json
    python3 scripts/compare_state_roots.py --self-test
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
from pathlib import Path


class RootsFileError(Exception):
    """A leg's roots file could not be read as a single JSON object."""


def _load(path: Path) -> dict[str, str]:
    raw = path.read_text(encoding="utf-8")
    try:
        data = json.loads(raw)
    except json.JSONDecodeError as exc:
        # A bare traceback here is actively misleading: it reads like a
        # determinism failure when it is a corrupt input file. The classic
        # cause is a `>` redirect capturing toolchain chatter ahead of the
        # JSON — under `cross`, rustup prints
        # "1.98.0-... unchanged - rustc 1.98.0 ..." to stdout, `json` parses
        # the leading "1.98" as a number, and the rest is reported as
        # "Extra data". Emitters must write with `--out`, not a redirect.
        preview = "\n".join(raw.splitlines()[:3]) or "<empty file>"
        raise RootsFileError(
            f"{path.name}: not a single JSON object ({exc}).\n"
            f"  This is a CORRUPT INPUT, not a state-root divergence.\n"
            f"  First lines were:\n    " + preview.replace("\n", "\n    ") + "\n"
            f"  If non-JSON text precedes the document, the emitter redirected "
            f"stdout instead of writing with --out."
        ) from exc
    if not isinstance(data, dict):
        raise RootsFileError(
            f"{path.name}: expected an object of height -> root, got {type(data).__name__}"
        )
    return {str(k): str(v) for k, v in data.items()}


def compare(files: list[Path], expected: Path | None = None) -> list[str]:
    """Return a list of error lines; empty means all legs agree AND match the anchor.

    `expected`, when given, is the committed anchor every leg is checked against
    in addition to being checked against one another. See the module docstring
    for why cross-leg agreement alone is not sufficient.
    """
    if len(files) < 2:
        return [f"need at least 2 root files to compare, got {len(files)}"]

    try:
        legs = {f.name: _load(f) for f in files}
    except RootsFileError as exc:
        return [str(exc)]
    errors: list[str] = []

    # Height-set agreement: every leg must cover the same heights.
    reference_name, reference = next(iter(legs.items()))
    ref_heights = set(reference)
    for name, roots in legs.items():
        missing = ref_heights - set(roots)
        extra = set(roots) - ref_heights
        if missing:
            errors.append(f"{name}: missing heights {sorted(missing, key=int)}")
        if extra:
            errors.append(f"{name}: unexpected heights {sorted(extra, key=int)}")

    # Per-height root agreement, reported at the FIRST divergent height.
    common_heights = sorted(set.intersection(*(set(r) for r in legs.values())), key=int)
    legs_diverged = False
    for height in common_heights:
        roots_here = {name: roots[height] for name, roots in legs.items()}
        distinct = set(roots_here.values())
        if len(distinct) > 1:
            legs_diverged = True
            errors.append(f"CROSS-LEG DIVERGENCE at height {height}:")
            for name in sorted(roots_here):
                errors.append(f"  {name}: {roots_here[name]}")
            errors.append(
                "  -> Nondeterminism: the same fixture produced different roots "
                "across build configurations."
            )
            # First divergent height is the actionable one; stop scanning roots.
            break

    if expected is None:
        return errors

    # --- Anchor check: every leg against the committed expected_roots.json -----
    #
    # This is the check that cannot be satisfied by the legs agreeing with each
    # other, because the anchor is committed rather than produced by this run.
    anchor = _load(expected)
    anchor_errors: list[str] = []

    for name in sorted(legs):
        roots = legs[name]
        missing = set(anchor) - set(roots)
        extra = set(roots) - set(anchor)
        if missing:
            anchor_errors.append(
                f"{name}: missing heights present in anchor {sorted(missing, key=int)}"
            )
        if extra:
            anchor_errors.append(
                f"{name}: heights absent from anchor {sorted(extra, key=int)}"
            )
        for height in sorted(set(roots) & set(anchor), key=int):
            if roots[height] != anchor[height]:
                anchor_errors.append(f"ANCHOR MISMATCH: {name} at height {height}:")
                anchor_errors.append(f"  expected ({expected.name}): {anchor[height]}")
                anchor_errors.append(f"  actual   ({name}): {roots[height]}")
                break  # first divergent height per leg is the actionable one

    if anchor_errors:
        errors.extend(anchor_errors)
        if not legs_diverged:
            # The dangerous case, called by its name: the legs are unanimous and
            # unanimously wrong. Cross-leg comparison alone would have passed this.
            errors.append("")
            errors.append(
                "  -> COMMON-MODE SHIFT: every leg agrees with every other leg, and "
                "all of them disagree with the committed anchor."
            )
            errors.append(
                "     This is a deterministic change to state-transition semantics, "
                "not a platform nondeterminism bug."
            )
            errors.append(
                "     Cross-leg comparison alone CANNOT detect this — the anchor is "
                "the only check that caught it."
            )
            errors.append(
                "     If the semantic change is intended, regenerate the fixture with "
                "REGENERATE_DETERMINISM_FIXTURE=1 and justify the "
                "expected_roots.json diff in the PR. Never regenerate to make this pass."
            )

    return errors


def self_test() -> None:
    with tempfile.TemporaryDirectory() as d:
        root = Path(d)
        a = root / "roots-a.json"
        b = root / "roots-b.json"
        c = root / "roots-c.json"
        a.write_text(json.dumps({"0": "aa", "1": "bb", "2": "cc"}), encoding="utf-8")
        b.write_text(json.dumps({"0": "aa", "1": "bb", "2": "cc"}), encoding="utf-8")
        # Divergent at height 1.
        c.write_text(json.dumps({"0": "aa", "1": "XX", "2": "cc"}), encoding="utf-8")

        assert compare([a, b]) == [], "identical legs must agree"

        errs = compare([a, b, c])
        assert any("height 1" in e for e in errs), errs
        assert any("XX" in e for e in errs), errs

        # Height-set mismatch is caught.
        short = root / "roots-short.json"
        short.write_text(json.dumps({"0": "aa", "1": "bb"}), encoding="utf-8")
        errs = compare([a, short])
        assert any("missing heights" in e for e in errs), errs

        # --- The anchor check: the case cross-leg comparison cannot see --------
        anchor = root / "expected_roots.json"
        anchor.write_text(json.dumps({"0": "aa", "1": "bb", "2": "cc"}), encoding="utf-8")

        # Legs agree with each other AND with the anchor -> pass.
        assert compare([a, b], anchor) == [], "matching legs + anchor must pass"

        # COMMON-MODE SHIFT: both legs moved together, away from the anchor.
        # This is the regression that motivated #2243 — cross-leg comparison
        # alone calls it green, so assert BOTH halves of that claim.
        shifted = {"0": "aa", "1": "SHIFTED", "2": "cc"}
        d = root / "roots-d.json"
        e = root / "roots-e.json"
        d.write_text(json.dumps(shifted), encoding="utf-8")
        e.write_text(json.dumps(shifted), encoding="utf-8")

        assert compare([d, e]) == [], (
            "REGRESSION: cross-leg comparison must still report unanimous legs as "
            "agreeing — if this now fails, the test below proves nothing"
        )
        errs = compare([d, e], anchor)
        assert any("ANCHOR MISMATCH" in x for x in errs), errs
        assert any("COMMON-MODE SHIFT" in x for x in errs), errs
        assert any("height 1" in x for x in errs), errs

        # A common-mode shift AND cross-leg divergence: report both, but do not
        # claim common-mode (the legs are not unanimous).
        f = root / "roots-f.json"
        f.write_text(json.dumps({"0": "aa", "1": "OTHER", "2": "cc"}), encoding="utf-8")
        errs = compare([d, f], anchor)
        assert any("CROSS-LEG DIVERGENCE" in x for x in errs), errs
        assert not any("COMMON-MODE SHIFT" in x for x in errs), errs

        # Anchor covering heights the legs lack is caught.
        long_anchor = root / "expected_long.json"
        long_anchor.write_text(
            json.dumps({"0": "aa", "1": "bb", "2": "cc", "3": "dd"}), encoding="utf-8"
        )
        errs = compare([a, b], long_anchor)
        assert any("missing heights present in anchor" in x for x in errs), errs
    print("compare_state_roots.py self-test passed (incl. anchor + common-mode cases)")


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("files", nargs="*", type=Path, help="root JSON files, >= 2")
    parser.add_argument(
        "--expected",
        type=Path,
        help="committed anchor (expected_roots.json) every leg must also match",
    )
    parser.add_argument(
        "--no-expected",
        action="store_true",
        help="skip the anchor check — ad-hoc local use only, NOT for CI",
    )
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()

    if args.self_test:
        self_test()
        return 0

    if args.expected and args.no_expected:
        print("error: --expected and --no-expected are mutually exclusive")
        return 2
    if not args.expected and not args.no_expected:
        # Failing closed here is the point. If omitting the anchor silently
        # degraded this to cross-leg-only, the gate would quietly return to being
        # unable to detect a common-mode shift — the exact defect #2243 fixed.
        print("error: no anchor given. Pass one of:")
        print(
            "  --expected tests/integration/fixtures/determinism/expected_roots.json"
            "   (what CI does)"
        )
        print("  --no-expected   (ad-hoc cross-leg diffing only; never in CI)")
        return 2

    # An anchor passed *as a leg* would be compared against itself and inflate the
    # leg count. Reject rather than silently double-count.
    if args.expected:
        resolved = {f.resolve() for f in args.files}
        if args.expected.resolve() in resolved:
            print(
                f"error: {args.expected} was passed as both the anchor and a leg. "
                "The anchor must be independent of the legs it checks."
            )
            return 2

    errors = compare(args.files, None if args.no_expected else args.expected)
    if errors:
        print("Determinism gate FAILED:")
        for line in errors:
            print(line)
        return 1

    if args.no_expected:
        print(
            f"All {len(args.files)} legs agree at every height. "
            "WARNING: no anchor checked (--no-expected), so a common-mode "
            "semantic shift would NOT have been detected."
        )
    else:
        print(
            f"All {len(args.files)} legs agree at every height, "
            f"and all match the committed anchor {args.expected.name}."
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
