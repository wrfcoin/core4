//! Integer twin of the `rmse_sigma` skill rule with anti-gaming on
//! ([`crate::skill`]), for the late forecast score.
//!
//! Everything here is integer arithmetic on fixed-point values (temperature in
//! 0.01 °C, pressure in Pa, …). There is no floating point, so every platform
//! computes the same number. The oracle job, the backend's practice score and
//! consensus all call the same functions, so the number a forecaster sees is
//! the number that is paid.
//!
//! ```text
//! err   = |forecast − truth|
//! copy  = |forecast − mean24| ≤ tol  or  |forecast − last| ≤ tol
//! skill = 0 if copy or ref == 0 or err ≥ ref
//!         else 1_000_000 − floor(1_000_000 · err / ref)
//! ```
//!
//! `ref` is the smaller of the window's population standard deviation and its
//! lagged-persistence RMSE ([`window_baselines`]); both are floored integer
//! square roots of exact integer quotients.
//!
//! Differences from the float rule, on purpose:
//!
//! - a zero reference always scores 0 (the float rule gives 1 for a zero error
//!   against a zero reference; a flat window carries no information to beat);
//! - every input is range checked and an out-of-range input is an error, never
//!   a clamped value (fail closed).
//!
//! Test vectors: `forecast-score/vectors/late_score_v1.json`, generated by an
//! independent big-integer implementation and checked by this crate's tests. A
//! port in another language is correct when it reproduces every case. Ports in
//! languages with 53-bit numbers must use big integers for `1_000_000 · err`.

use serde::{Deserialize, Serialize};
use sha3::{Digest, Sha3_256};

/// Skill is expressed in millionths: `1_000_000` is a perfect forecast.
pub const SKILL_PRECISION: u64 = 1_000_000;

/// Largest absolute fixed-point value accepted for a forecast, truth, mean or
/// last reading. 10^9 covers every supported unit with room to spare
/// (10^9 centi-degrees, 10^9 Pa) and keeps every intermediate far below
/// `u128::MAX` (see the bounds noted at each multiply).
pub const MAX_ABS_VALUE: i64 = 1_000_000_000;

/// Largest reference error accepted: no window of values within
/// ±[`MAX_ABS_VALUE`] can have a spread or a persistence error above the full
/// range.
pub const MAX_REFERENCE: u64 = 2_000_000_000;

/// Largest copy tolerance accepted.
pub const MAX_COPY_TOLERANCE: u64 = 1_000_000;

/// Default copy tolerance in fixed-point units: 5 = 0.05 °C, the integer form
/// of [`crate::skill::DEFAULT_COPY_TOLERANCE`].
pub const DEFAULT_COPY_TOLERANCE_UNITS: u64 = 5;

/// Most readings a baseline window may hold.
pub const MAX_WINDOW_LEN: usize = 4_096;

/// Domain tag of [`window_hash`].
pub const WINDOW_HASH_DOMAIN: &[u8] = b"wrfcoin.forecast_late_score.window.v1";

/// The inputs of one score. `reference`, `mean24` and `last` come from the
/// observation (see [`window_baselines`]); `forecast` is the forecaster's value.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LateScoreInput {
    pub forecast: i64,
    pub truth: i64,
    pub reference: u64,
    pub mean24: i64,
    pub last: i64,
    pub tolerance: u64,
}

/// Which baseline a forecast copied.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum CopiedBaseline {
    /// Within tolerance of the 24 h mean (checked first).
    Mean24,
    /// Within tolerance of the last reading before issue.
    Last,
}

/// The result of one score.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LateScore {
    /// Skill in millionths, `0..=SKILL_PRECISION`.
    pub skill: u64,
    /// `|forecast − truth|` in fixed-point units.
    pub err: u64,
    /// Set when the forecast copied a baseline (skill is then 0).
    pub copied: Option<CopiedBaseline>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum LateScoreError {
    #[error("forecast, truth, mean24 or last is outside ±MAX_ABS_VALUE")]
    ValueOutOfRange,
    #[error("reference is above MAX_REFERENCE")]
    ReferenceOutOfRange,
    #[error("copy tolerance is above MAX_COPY_TOLERANCE")]
    ToleranceOutOfRange,
    #[error("window needs between 2 and MAX_WINDOW_LEN readings")]
    WindowLength,
    #[error("arithmetic overflow")]
    Overflow,
}

const fn value_in_range(v: i64) -> bool {
    v >= -MAX_ABS_VALUE && v <= MAX_ABS_VALUE
}

/// True when `value` is an acceptable fixed-point forecast or reading.
pub const fn is_valid_value(value: i64) -> bool {
    value_in_range(value)
}

/// Score one forecast against one observation.
///
/// Pure integer arithmetic. Bounds: `err ≤ 2·10^9`, so
/// `SKILL_PRECISION · err ≤ 2·10^15`, computed in `u128` with checked
/// operations regardless.
pub fn late_skill(input: &LateScoreInput) -> Result<LateScore, LateScoreError> {
    if !(value_in_range(input.forecast)
        && value_in_range(input.truth)
        && value_in_range(input.mean24)
        && value_in_range(input.last))
    {
        return Err(LateScoreError::ValueOutOfRange);
    }
    if input.reference > MAX_REFERENCE {
        return Err(LateScoreError::ReferenceOutOfRange);
    }
    if input.tolerance > MAX_COPY_TOLERANCE {
        return Err(LateScoreError::ToleranceOutOfRange);
    }
    // `abs_diff` on i64 cannot overflow: the result is a u64.
    let err = input.forecast.abs_diff(input.truth);
    let copied = if input.forecast.abs_diff(input.mean24) <= input.tolerance {
        Some(CopiedBaseline::Mean24)
    } else if input.forecast.abs_diff(input.last) <= input.tolerance {
        Some(CopiedBaseline::Last)
    } else {
        None
    };
    if copied.is_some() || input.reference == 0 || err >= input.reference {
        return Ok(LateScore {
            skill: 0,
            err,
            copied,
        });
    }
    // err < reference here, so the quotient is < SKILL_PRECISION.
    let lost = u128::from(SKILL_PRECISION)
        .checked_mul(u128::from(err))
        .and_then(|n| n.checked_div(u128::from(input.reference)))
        .ok_or(LateScoreError::Overflow)?;
    let lost = u64::try_from(lost).map_err(|_| LateScoreError::Overflow)?;
    let skill = SKILL_PRECISION
        .checked_sub(lost)
        .ok_or(LateScoreError::Overflow)?;
    Ok(LateScore { skill, err, copied })
}

/// Which spread [`window_baselines`] chose as the reference.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ReferenceSource {
    ClimatologySpread,
    PersistenceSpread,
}

/// The oracle-side numbers derived from a station's reading window.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct WindowBaselines {
    /// `min(spread, lagged persistence error)`; the spread when the window is
    /// too short for the lag, or on a tie.
    pub reference: u64,
    pub reference_source: ReferenceSource,
    /// Window mean, floored (rounded toward negative infinity).
    pub mean24: i64,
    /// The most recent reading in the window.
    pub last: i64,
}

/// Floor of the square root of `n` (Newton's method on integers).
pub fn isqrt_u128(n: u128) -> u128 {
    if n < 2 {
        return n;
    }
    // Start at a power of two that is ≥ sqrt(n), then descend monotonically.
    let bits = 128 - n.leading_zeros();
    let mut x: u128 = 1u128 << bits.div_ceil(2);
    loop {
        // x ≥ 1 always: the sequence decreases to floor(sqrt(n)) ≥ 1.
        let y = (x + n / x) >> 1;
        if y >= x {
            return x;
        }
        x = y;
    }
}

/// Integer baselines of a time-ordered reading window (oldest first, last =
/// most recent before issue). `lag_steps` is the forecast lead in window
/// samples; `0` is treated as `1`.
///
/// - spread = `isqrt(floor((n·Σx² − (Σx)²) / n²))` (population standard deviation)
/// - persistence = `isqrt(floor(Σ(x[i+lag] − x[i])² / (n − lag)))`
///
/// Bounds with `|x| ≤ 10^9` and `n ≤ 4096`: `Σx² ≤ 4.1·10^21`,
/// `n·Σx² ≤ 1.7·10^25`, `(Σx)² ≤ 1.7·10^25`, squared differences
/// `≤ 4·10^18` each; all far below `u128::MAX ≈ 3.4·10^38`. Checked anyway.
pub fn window_baselines(
    window: &[i64],
    lag_steps: usize,
) -> Result<WindowBaselines, LateScoreError> {
    let len = window.len();
    if !(2..=MAX_WINDOW_LEN).contains(&len) {
        return Err(LateScoreError::WindowLength);
    }
    if !window.iter().all(|v| value_in_range(*v)) {
        return Err(LateScoreError::ValueOutOfRange);
    }
    let n = len as u128;
    let mut sum: i128 = 0;
    let mut sum_sq: u128 = 0;
    for v in window {
        let v = i128::from(*v);
        sum = sum.checked_add(v).ok_or(LateScoreError::Overflow)?;
        let sq = v.checked_mul(v).ok_or(LateScoreError::Overflow)?;
        sum_sq = sum_sq
            .checked_add(sq.unsigned_abs())
            .ok_or(LateScoreError::Overflow)?;
    }
    let sum_abs = sum.unsigned_abs();
    let n_sum_sq = n.checked_mul(sum_sq).ok_or(LateScoreError::Overflow)?;
    let sum_squared = sum_abs
        .checked_mul(sum_abs)
        .ok_or(LateScoreError::Overflow)?;
    // Cauchy–Schwarz: n·Σx² ≥ (Σx)². A failure here means a broken invariant.
    let numerator = n_sum_sq
        .checked_sub(sum_squared)
        .ok_or(LateScoreError::Overflow)?;
    let n_sq = n.checked_mul(n).ok_or(LateScoreError::Overflow)?;
    let spread = isqrt_u128(numerator / n_sq);

    let lag = lag_steps.max(1);
    let persistence = if len > lag {
        let pairs = len - lag;
        let mut sq: u128 = 0;
        for i in 0..pairs {
            let d = u128::from(window[i + lag].abs_diff(window[i]));
            let d2 = d.checked_mul(d).ok_or(LateScoreError::Overflow)?;
            sq = sq.checked_add(d2).ok_or(LateScoreError::Overflow)?;
        }
        Some(isqrt_u128(sq / pairs as u128))
    } else {
        None
    };

    let (reference, reference_source) = match persistence {
        Some(p) if p < spread => (p, ReferenceSource::PersistenceSpread),
        _ => (spread, ReferenceSource::ClimatologySpread),
    };
    let reference = u64::try_from(reference).map_err(|_| LateScoreError::Overflow)?;
    if reference > MAX_REFERENCE {
        return Err(LateScoreError::Overflow);
    }
    let mean24 =
        i64::try_from(sum.div_euclid(len as i128)).map_err(|_| LateScoreError::Overflow)?;
    Ok(WindowBaselines {
        reference,
        reference_source,
        mean24,
        last: window[len - 1],
    })
}

/// Hash that binds an observation attestation to the exact readings used:
/// `SHA3-256(domain ‖ u32_be(n) ‖ for each reading: i64_be(timestamp) ‖ i64_be(value))`.
pub fn window_hash(readings: &[(i64, i64)]) -> Result<[u8; 32], LateScoreError> {
    let len = u32::try_from(readings.len()).map_err(|_| LateScoreError::WindowLength)?;
    if readings.len() > MAX_WINDOW_LEN {
        return Err(LateScoreError::WindowLength);
    }
    let mut hasher = Sha3_256::new();
    hasher.update(WINDOW_HASH_DOMAIN);
    hasher.update(len.to_be_bytes());
    for (timestamp, value) in readings {
        hasher.update(timestamp.to_be_bytes());
        hasher.update(value.to_be_bytes());
    }
    Ok(hasher.finalize().into())
}

#[cfg(test)]
mod tests {
    use super::*;

    const VECTORS: &str = include_str!("../vectors/late_score_v1.json");

    #[derive(Deserialize)]
    #[serde(deny_unknown_fields)]
    struct Vectors {
        version: u32,
        skill_precision: u64,
        max_abs_value: i64,
        max_reference: u64,
        max_copy_tolerance: u64,
        default_copy_tolerance: u64,
        #[allow(dead_code)]
        notes: Vec<String>,
        skill_cases: Vec<SkillCase>,
        baseline_cases: Vec<BaselineCase>,
        window_hash_cases: Vec<WindowHashCase>,
    }

    #[derive(Deserialize)]
    #[serde(deny_unknown_fields)]
    struct SkillCase {
        name: String,
        input: LateScoreInput,
        expect: Option<LateScore>,
        expect_error: Option<String>,
    }

    #[derive(Deserialize)]
    #[serde(deny_unknown_fields)]
    struct BaselineCase {
        name: String,
        window: Vec<i64>,
        lag_steps: usize,
        expect: Option<WindowBaselines>,
        expect_error: Option<String>,
    }

    #[derive(Deserialize)]
    #[serde(deny_unknown_fields)]
    struct WindowHashCase {
        name: String,
        readings: Vec<(i64, i64)>,
        expect_hex: String,
    }

    fn error_name(e: LateScoreError) -> &'static str {
        match e {
            LateScoreError::ValueOutOfRange => "value_out_of_range",
            LateScoreError::ReferenceOutOfRange => "reference_out_of_range",
            LateScoreError::ToleranceOutOfRange => "tolerance_out_of_range",
            LateScoreError::WindowLength => "window_length",
            LateScoreError::Overflow => "overflow",
        }
    }

    fn vectors() -> Vectors {
        serde_json::from_str(VECTORS).expect("vectors parse")
    }

    #[test]
    fn vector_header_matches_constants() {
        let v = vectors();
        assert_eq!(v.version, 1);
        assert_eq!(v.skill_precision, SKILL_PRECISION);
        assert_eq!(v.max_abs_value, MAX_ABS_VALUE);
        assert_eq!(v.max_reference, MAX_REFERENCE);
        assert_eq!(v.max_copy_tolerance, MAX_COPY_TOLERANCE);
        assert_eq!(v.default_copy_tolerance, DEFAULT_COPY_TOLERANCE_UNITS);
    }

    /// Platform-neutral golden test: the expected numbers were produced by an
    /// independent big-integer implementation, not by this code.
    #[test]
    fn skill_vectors_match() {
        let v = vectors();
        assert!(v.skill_cases.len() >= 40, "vector file lost cases");
        for case in &v.skill_cases {
            let got = late_skill(&case.input);
            match (&case.expect, &case.expect_error) {
                (Some(expect), None) => assert_eq!(got.as_ref(), Ok(expect), "case {}", case.name),
                (None, Some(name)) => {
                    assert_eq!(
                        got.map_err(error_name),
                        Err(name.as_str()),
                        "case {}",
                        case.name
                    )
                },
                _ => panic!(
                    "case {} needs exactly one of expect / expect_error",
                    case.name
                ),
            }
        }
    }

    #[test]
    fn baseline_vectors_match() {
        let v = vectors();
        assert!(v.baseline_cases.len() >= 12, "vector file lost cases");
        for case in &v.baseline_cases {
            let got = window_baselines(&case.window, case.lag_steps);
            match (&case.expect, &case.expect_error) {
                (Some(expect), None) => assert_eq!(got.as_ref(), Ok(expect), "case {}", case.name),
                (None, Some(name)) => {
                    assert_eq!(
                        got.map_err(error_name),
                        Err(name.as_str()),
                        "case {}",
                        case.name
                    )
                },
                _ => panic!(
                    "case {} needs exactly one of expect / expect_error",
                    case.name
                ),
            }
        }
    }

    #[test]
    fn window_hash_vectors_match() {
        let v = vectors();
        assert!(!v.window_hash_cases.is_empty());
        for case in &v.window_hash_cases {
            let got = window_hash(&case.readings).expect("hash");
            assert_eq!(hex::encode(got), case.expect_hex, "case {}", case.name);
        }
    }

    #[test]
    fn skill_is_never_above_precision_and_monotone_in_error() {
        // Exhaustive over a small grid: skill never rises as the error grows.
        for reference in [1u64, 2, 3, 7, 100, 999_983, MAX_REFERENCE] {
            let mut previous = SKILL_PRECISION;
            for err in 0..=40i64 {
                let s = late_skill(&LateScoreInput {
                    forecast: err,
                    truth: 0,
                    reference,
                    mean24: -1_000_000,
                    last: -1_000_000,
                    tolerance: 0,
                })
                .expect("in range");
                assert!(s.skill <= SKILL_PRECISION);
                assert!(s.skill <= previous, "ref {reference} err {err}");
                previous = s.skill;
            }
        }
    }

    #[test]
    fn isqrt_is_the_floor_root() {
        for n in 0u128..2_000 {
            let r = isqrt_u128(n);
            assert!(r * r <= n && (r + 1) * (r + 1) > n, "n {n}");
        }
        for n in [
            u128::from(u64::MAX),
            u128::MAX,
            (1u128 << 100) - 1,
            1u128 << 100,
            4_000_000_000_000_000_000,
        ] {
            let r = isqrt_u128(n);
            assert!(r.checked_mul(r).is_some_and(|sq| sq <= n), "n {n}");
            assert!((r + 1).checked_mul(r + 1).is_none_or(|sq| sq > n), "n {n}");
        }
    }

    #[test]
    fn extreme_window_does_not_overflow() {
        let mut window = vec![MAX_ABS_VALUE; MAX_WINDOW_LEN / 2];
        window.extend(vec![-MAX_ABS_VALUE; MAX_WINDOW_LEN / 2]);
        let b = window_baselines(&window, 1).expect("extreme window is in range");
        // One jump of 2·10^9 among 4095 pairs.
        assert_eq!(b.reference_source, ReferenceSource::PersistenceSpread);
        assert_eq!(b.mean24, 0);
        assert!(b.reference <= MAX_REFERENCE);
    }

    /// The integer rule tracks the float rule on ordinary inputs (to within
    /// rounding of the integer square root); it is not a consensus property.
    #[test]
    fn tracks_the_float_rule_on_ordinary_inputs() {
        use crate::skill::{AntiGaming, SkillDefinition, VariableInput, score_forecast};
        use std::collections::BTreeMap;

        let window_c = [
            18.2, 18.9, 19.7, 21.3, 22.8, 23.1, 22.4, 21.0, 19.6, 18.8, 18.1, 17.7,
        ];
        let window: Vec<i64> = window_c
            .iter()
            .map(|c: &f64| (c * 100.0).round() as i64)
            .collect();
        let b = window_baselines(&window, 1).expect("baselines");
        let (forecast_c, truth_c) = (20.4, 20.9);
        let int = late_skill(&LateScoreInput {
            forecast: 2040,
            truth: 2090,
            reference: b.reference,
            mean24: b.mean24,
            last: b.last,
            tolerance: DEFAULT_COPY_TOLERANCE_UNITS,
        })
        .expect("score");
        let mut vars = BTreeMap::new();
        vars.insert(
            "temp_c".to_string(),
            VariableInput {
                forecast: forecast_c,
                truth: truth_c,
                window: window_c.to_vec(),
                reference_forecasts: vec![],
            },
        );
        let float = score_forecast(
            &vars,
            SkillDefinition::RmseSigma,
            &AntiGaming {
                enabled: true,
                copy_tolerance: BTreeMap::new(),
                persistence_lag_steps: 1,
            },
        )
        .expect("float score");
        let float_millionths = (float.metrics.skill_score * 1_000_000.0).round() as i64;
        assert!(
            (float_millionths - int.skill as i64).abs() < 10_000,
            "float {float_millionths} int {}",
            int.skill
        );
    }
}
